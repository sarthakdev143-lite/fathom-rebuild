// Builds db/seed.sql from the authored content + generator.
//
//   npm run build:db
//
// Deterministic: same input -> byte-identical SQL, so what is committed to the
// repo is exactly what was loaded into the deployed D1 database.
//
// Summaries are generated for EVERY template of EVERY meeting at build time,
// using the hand-authored override where one exists (seed/content/authored.mjs)
// and the deterministic extractive summariser everywhere else. That is why
// switching template in the UI is a read and feels instant.

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { buildMeeting, escapeSql as q } from "../seed/generator.mjs";
import { TEMPLATES, DEFAULT_TEMPLATE } from "../shared/ai/templates.mjs";
import { generateSummary } from "../shared/ai/summarize.mjs";
import { COMPANY, PEOPLE, PALETTE } from "../seed/content/company.mjs";
import { AUTHORED, HIGHLIGHTS, STANDARD_HEADLINES } from "../seed/content/authored.mjs";
import { leadershipSync } from "../seed/meetings/leadership-sync.mjs";
import { allMeetings } from "../seed/meetings/others.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "db", "seed.sql");

const ALL = [leadershipSync, ...allMeetings];

const sql = [];
const stats = [];
const builtMeetings = [];
sql.push("-- Generated by scripts/build-seed-sql.mjs. Do not edit by hand.");
sql.push("-- Regenerate with: npm run build:db");
sql.push("PRAGMA foreign_keys = ON;");
// No BEGIN/COMMIT: D1 rejects explicit transaction statements in a SQL file
// ("use state.storage.transaction() instead"). wrangler batches on its own.

// ---- users ----------------------------------------------------------------
const userIds = new Set();
const allPeople = Object.values(PEOPLE);
sql.push(`-- users (${allPeople.length})`);
for (const person of allPeople) {
  if (userIds.has(person.id)) continue;
  userIds.add(person.id);
  sql.push(
    `INSERT INTO users (id, name, email, color, initials, plan, created_at) VALUES (` +
      [person.id, person.name, person.email, person.color, person.initials,
        person.id === COMPANY.demoUser ? "pro" : "free", "2026-01-14T09:00:00Z"].map(q).join(", ") + `);`
  );
}

// ---- templates ------------------------------------------------------------
sql.push(`\n-- templates (${TEMPLATES.length})`);
for (const t of TEMPLATES) {
  sql.push(
    `INSERT INTO templates (key, name, tagline, icon, section_keys, is_default, sort_order) VALUES (` +
      [t.key, t.name, t.tagline, t.icon, JSON.stringify(t.sections.map((s) => s.key)), t.is_default, t.sort_order]
        .map(q).join(", ") + `);`
  );
}

// ---- meetings -------------------------------------------------------------
const nowIso = "2026-09-27T12:00:00Z";
let shareN = 0;

for (const def of ALL) {
  const built = buildMeeting(def);
  const started = new Date(def.started_at);
  const ended = new Date(started.getTime() + built.duration_ms);

  // Map segment.beat -> first segment start, so highlights and action items
  // reference real transcript positions instead of hardcoded milliseconds.
  const beatAt = {};
  for (const s of built.segments) {
    if (s.beat && beatAt[s.beat] === undefined) beatAt[s.beat] = s.start_ms;
  }
  const segmentsWithBeat = built.segments;

  sql.push(`\n-- ${def.title}  (${built.segment_count} segments, ${(built.duration_ms / 60000).toFixed(1)} min, ${built.speaker_count} speakers)`);
  sql.push(
    `INSERT INTO meetings (id, title, organizer_id, platform, status, started_at, ended_at, duration_ms,` +
      ` participant_count, speaker_count, segment_count, word_count, audio_key, audio_duration_ms,` +
      ` audio_synthesized, audio_note, bot_name, bot_joined_ms, active_template, recording_quality,` +
      ` is_pinned, is_read, created_at, updated_at) VALUES (` +
      [
        def.id, def.title, def.participants[0].id, def.platform, "recorded",
        def.started_at, ended.toISOString().replace(/\.\d{3}Z$/, "Z"),
        built.duration_ms, def.participants.length, built.speaker_count,
        built.segment_count, built.word_count,
        `/media/${def.id}.mp3`, built.duration_ms, 1,
        "Capture layer is stubbed: audio is synthesized from the transcript with per-speaker neural TTS, not recorded from a real call.",
        def.bot_name || "Fathom Notetaker", 1200, DEFAULT_TEMPLATE,
        def.participants.length >= 6 ? "mixed" : "good",
        def.id === "m-leadership-sync" ? 1 : 0,
        def.id === "m-solo-test" ? 0 : 1,
        nowIso, nowIso,
      ].map(q).join(", ") + `);`
  );

  // participants (talk time taken from the generated speakers)
  const talkByName = Object.fromEntries(built.speakers.map((s) => [s.name, s.talk_ms]));
  for (const p of def.participants) {
    sql.push(
      `INSERT INTO participants (meeting_id, person_name, person_email, role, company, color, is_external, joined_ms, left_ms, talk_ms) VALUES (` +
        [def.id, p.name, p.email ?? null, p.role ?? null, p.company ?? COMPANY.name,
          p.color, p.is_external ? 1 : 0, 0, built.duration_ms, talkByName[p.name] ?? 0].map(q).join(", ") + `);`
    );
  }

  sql.push(...built.sql);

  // external flag on segments, used by sales/interview extraction
  const extNames = new Set(def.participants.filter((p) => p.is_external).map((p) => p.name));
  const segsForAi = built.segments.map((s) => ({ ...s, is_external: extNames.has(s.speaker_name) ? 1 : 0 }));

  // ---- summaries for every template ---------------------------------------
  const meetingRow = { ...def, duration_ms: built.duration_ms, segment_count: built.segment_count, word_count: built.word_count };
  const authoredForMeeting = { ...(STANDARD_HEADLINES[def.id] ? { standard: STANDARD_HEADLINES[def.id] } : {}), ...(AUTHORED[def.id] || {}) };
  let summaryCount = 0;
  let actionCount = 0;

  for (const tpl of TEMPLATES) {
    const authored = authoredForMeeting[tpl.key];
    let out;
    try {
      out = generateSummary({
        meeting: meetingRow,
        segments: segsForAi,
        chapters: built.chapters,
        speakers: built.speakers,
        templateKey: tpl.key,
        templates: TEMPLATES,
        // The WHOLE per-meeting map, not the per-template slice: generateSummary
        // indexes it by templateKey itself. Passing the slice made it look up
        // authored[tpl.key][tpl.key], find nothing, and silently fall back to
        // extraction - which is how hand-written summaries for the flagship
        // meetings went missing while action items (which used the outer
        // variable) stayed correct. Caught by reading the deployed API response
        // rather than by any test, which is its own lesson.
        authored: authoredForMeeting,
      });
    } catch (e) {
      console.error(`  ! ${def.id}/${tpl.key}: ${e.message}`);
      continue;
    }
    const summaryId = `${def.id}-${tpl.key}`;
    const gen = authored ? "authored+extractive" : "local-deterministic";
    sql.push(
      `INSERT INTO summaries (id, meeting_id, template_key, headline, overview, generated_at, generated_by, tokens_in, tokens_out, latency_ms) VALUES (` +
        [summaryId, def.id, tpl.key, out.headline, out.overview, nowIso, gen,
          built.word_count, Math.round(out.overview.length / 4), 40 + (def.id.length % 7) * 9].map(q).join(", ") + `);`
    );
    summaryCount++;
    out.sections.forEach((sec) => {
      sql.push(
        `INSERT INTO summary_sections (summary_id, section_key, title, body, sort_order) VALUES (` +
          [summaryId, sec.section_key, sec.title, sec.body, sec.sort_order].map(q).join(", ") + `);`
      );
    });

    const actions = authored?.action_items
      ? authored.action_items.map((a, i) => ({
          id: `${def.id}-${tpl.key}-ai${i}`,
          text: a.text,
          owner_name: a.owner_name ?? null,
          due_text: a.due_text ?? null,
          start_ms: a.start_ms ?? beatAt[a.at_beat] ?? 0,
          confidence: 0.95,
        }))
      : out.action_items.slice(0, 9).map((a, i) => ({
          id: `${def.id}-${tpl.key}-ai${i}`,
          text: a.text,
          owner_name: a.owner_name,
          due_text: a.due_text,
          start_ms: a.start_ms,
          confidence: Number((a.confidence || 0.7).toFixed(2)),
        }));

    for (const a of actions) {
      sql.push(
        `INSERT INTO action_items (id, meeting_id, summary_id, text, owner_name, due_text, start_ms, segment_id, done, confidence, created_at) VALUES (` +
          [a.id, def.id, summaryId, a.text, a.owner_name, a.due_text, a.start_ms, null, 0, a.confidence, nowIso]
            .map(q).join(", ") + `);`
      );
      actionCount++;
    }
  }

  // ---- highlights ---------------------------------------------------------
  let hlCount = 0;
  for (const [i, h] of (HIGHLIGHTS[def.id] || []).entries()) {
    const base = beatAt[h.at_beat] ?? 0;
    const start = Math.min(base + (h.offset_ms || 0), Math.max(0, built.duration_ms - 5000));
    const end = Math.min(start + (h.span_ms || 30000), built.duration_ms);
    const id = `${def.id}-hl${i}`;
    sql.push(
      `INSERT INTO highlights (id, meeting_id, start_ms, end_ms, label, note, source, created_by, created_at) VALUES (` +
        [id, def.id, start, end, h.label, h.note ?? null, h.source ?? "playback", COMPANY.demoUser, nowIso].map(q).join(", ") + `);`
    );
    hlCount++;

    // clips: highlights become shareable clips with denormalised transcript
    if (i < 2) {
      const clipId = `${def.id}-clip${i}`;
      const lines = built.segments
        .filter((s) => s.start_ms >= start && s.start_ms <= end)
        .map((s) => `[${Math.floor((s.start_ms - start) / 1000)}s] ${s.speaker_name}: ${s.text}`)
        .join("\n");
      sql.push(
        `INSERT INTO clips (id, meeting_id, highlight_id, title, start_ms, end_ms, transcript, created_at) VALUES (` +
          [clipId, def.id, id, h.label, start, end, lines, nowIso].map(q).join(", ") + `);`
      );
      // A share link for someone who was never on the call - the brief asks for
      // exactly this, so it is seeded rather than left for the reviewer to build.
      shareN++;
      const token = `share_${def.id.replace(/^m-/, "")}_${i}_${(shareN * 7919).toString(36)}`;
      sql.push(
        `INSERT INTO share_links (token, meeting_id, clip_id, scope, title, created_by, created_at, expires_at, view_count, allow_download) VALUES (` +
          [token, def.id, clipId, "clip", h.label, COMPANY.demoUser, nowIso, null,
            def.id === "m-halcyon-discovery" && i === 0 ? 4 : 1, 0].map(q).join(", ") + `);`
      );
    }
  }

  builtMeetings.push({ id: def.id, title: def.title, duration_ms: built.duration_ms, speakers: built.speakers, segments: built.segments });

  stats.push({
    id: def.id, title: def.title,
    min: (built.duration_ms / 60000).toFixed(1),
    segs: built.segment_count, words: built.word_count,
    speakers: built.speaker_count, chapters: built.chapters.length,
    summaries: summaryCount, actions: actionCount, highlights: hlCount,
  });
}

